"""Фильтрация закупок после загрузки с ЕИС.

Что уже сделал ЕИС на своёй стороне:
  - морфологический поиск по ключевым словам (searchString + morphology=on)
  - фильтрация по региону (customerPlace)
  - фильтрация по ИНН заказчика (customerIdOrg)
  - фильтрация по датам публикации

Что мы делаем дополнительно:
  - убираем дубликаты по external_id (уже виденные ранее записи)
  - если заданы конкретные ИНН — дополнительная проверка (на случай если еИС
    вернул лишнее по какой-то причине)
Ключевые слова не проверяются повторно — ЕИС уже сделал морфологический поиск.
"""

from typing import List, Dict


def apply_filters(tenders: List[Dict], profile: Dict) -> List[Dict]:
    """
    Постфильтрация. ЕИС уже отфильтровал по региону/ключам/ИНН.
    Здесь только дополнительная проверка по ИНН, если он задан и не передавался в параметрах запроса.
    """
    inn_list = [i.strip() for i in (profile.get("inn_list") or []) if i.strip()]

    # Если ИНН не заданы — все записи проходят
    if not inn_list:
        return tenders

    # Если ИНН заданы — проверяем (на случай если еИС не отфильтровал чётко)
    return [
        t for t in tenders
        if (t.get("customer_inn") or "").strip() in inn_list
    ]
